<#
.SYNOPSIS
    Builds the report object and exports it to JSON, HTML, or technical log formats.

.DESCRIPTION
    Generates a contract-compliant report object (schema_version 0.1),
    computes summary counters from control results, and writes UTF-8
    (no BOM) output files.
    Never modifies system state (except writing the requested output file).
#>

Set-StrictMode -Version 2

function New-Report {
    <#
    .SYNOPSIS
        Builds the report object from control results.
    .PARAMETER Risultati
        Array of control results (from Invoke-Controlli).
    .PARAMETER Ambiente
        Environment object (from Get-AmbienteSistema).
    .PARAMETER Catalogo
        Catalog object (from Import-Catalogo).
    .PARAMETER VersioneTool
        Scanner tool version string.
    .OUTPUTS
        PSCustomObject conforming to the report schema contract.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [AllowEmptyCollection()]
        [array]$Risultati,

        [Parameter(Mandatory = $true)]
        [PSCustomObject]$Ambiente,

        [Parameter(Mandatory = $true)]
        [PSCustomObject]$Catalogo,

        [Parameter(Mandatory = $false)]
        [string]$VersioneTool = '0.1.0'
    )

    $risultatiArray = if ($null -eq $Risultati) { @() } else { @($Risultati) }

    # Compute summary counters
    $riepilogo = @{
        superato         = 0
        fallito          = 0
        non_applicabile  = 0
        sconosciuto      = 0
        errore           = 0
    }

    foreach ($r in $risultatiArray) {
        if ($riepilogo.ContainsKey($r.status)) {
            $riepilogo[$r.status] = $riepilogo[$r.status] + 1
        }
    }

    # Build the report object
    $report = [PSCustomObject]@{
        schema_version  = '0.1'
        run_id          = [guid]::NewGuid().ToString()
        timestamp       = (Get-Date).ToUniversalTime().ToString('o')
        tool_version    = $VersioneTool
        catalog_version = $Catalogo.schema_version
        environment     = [PSCustomObject]@{
            edition    = $Ambiente.Edition
            build      = $Ambiente.Build
            language   = $Ambiente.Language
            is_admin   = $Ambiente.IsAdmin
            ps_version = $Ambiente.PsVersion
        }
        results         = $risultatiArray
        summary         = [PSCustomObject]@{
            superato        = $riepilogo['superato']
            fallito         = $riepilogo['fallito']
            non_applicabile = $riepilogo['non_applicabile']
            sconosciuto     = $riepilogo['sconosciuto']
            errore          = $riepilogo['errore']
        }
    }

    return $report
}

function Export-ReportJson {
    <#
    .SYNOPSIS
        Writes the report to a JSON file in UTF-8 without BOM.
    .PARAMETER Report
        The report object to serialize.
    .PARAMETER PercorsoFile
        Destination JSON file path.
    .NOTES
        Uses [System.IO.File]::WriteAllText with UTF8Encoding($false) to
        guarantee UTF-8 without BOM.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [PSCustomObject]$Report,

        [Parameter(Mandatory = $true)]
        [string]$PercorsoFile
    )

    # Convert to JSON with sufficient depth
    $json = $Report | ConvertTo-Json -Depth 10

    # Write as UTF-8 without BOM
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($PercorsoFile, $json, $utf8NoBom)
}

function ConvertTo-ReportHtml {
    <#
    .SYNOPSIS
        Converts a Report object (and optional Catalog) into a standalone HTML document.
    .PARAMETER Report
        The report object generated by New-Report.
    .PARAMETER Catalogo
        Optional catalog object used to enrich rows with titles, severity, and categories.
    .OUTPUTS
        Self-contained HTML string with embedded CSS and no external dependencies.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [PSCustomObject]$Report,

        [Parameter(Mandatory = $false)]
        [PSCustomObject]$Catalogo = $null
    )

    # Fast lookup map for catalog controls by ID
    $mappaCatalogo = @{}
    if ($null -ne $Catalogo -and $null -ne $Catalogo.PSObject.Properties['controls'] -and $null -ne $Catalogo.controls) {
        foreach ($c in $Catalogo.controls) {
            if ($null -ne $c.PSObject.Properties['id'] -and $c.id) {
                $mappaCatalogo[$c.id] = $c
            }
        }
    }

    $escapeHtml = {
        param([AllowNull()][string]$Testo)
        if ([string]::IsNullOrEmpty($Testo)) { return '' }
        return [System.Net.WebUtility]::HtmlEncode($Testo)
    }

    $righeHtml = New-Object System.Text.StringBuilder
    $risultatiLista = if ($null -ne $Report.results) { @($Report.results) } else { @() }

    foreach ($r in $risultatiLista) {
        $id = [string]$r.control_id
        $stato = [string]$r.status
        $titolo = $id
        $categoria = '-'
        $gravita = '-'
        $spiegazione = ''

        if ($mappaCatalogo.ContainsKey($id)) {
            $meta = $mappaCatalogo[$id]
            if ($null -ne $meta.PSObject.Properties['title'] -and $meta.title) { $titolo = [string]$meta.title }
            if ($null -ne $meta.PSObject.Properties['category'] -and $meta.category) { $categoria = [string]$meta.category }
            if ($null -ne $meta.PSObject.Properties['severity'] -and $meta.severity) {
                $gravita = switch ([string]$meta.severity) {
                    'critico'     { 'Critical' }
                    'alto'        { 'High' }
                    'medio'       { 'Medium' }
                    'basso'       { 'Low' }
                    'informativo' { 'Info' }
                    default       { [string]$meta.severity }
                }
            }
            if ($null -ne $meta.PSObject.Properties['rationale'] -and $meta.rationale) { $spiegazione = [string]$meta.rationale }
        }

        $simboloStato = '[?]'
        $etichettaStato = 'Unknown'
        $classeStato = 'stato-sconosciuto'
        switch ($stato) {
            'superato'        { $simboloStato = '[OK]'; $etichettaStato = 'Passed';  $classeStato = 'stato-superato' }
            'fallito'         { $simboloStato = '[X]';  $etichettaStato = 'Failed';  $classeStato = 'stato-fallito' }
            'sconosciuto'     { $simboloStato = '[?]';  $etichettaStato = 'Unknown'; $classeStato = 'stato-sconosciuto' }
            'errore'          { $simboloStato = '[!]';  $etichettaStato = 'Error';   $classeStato = 'stato-errore' }
            'non_applicabile' { $simboloStato = '[-]';  $etichettaStato = 'N/A';     $classeStato = 'stato-na' }
        }

        $osservatoStr = if ($null -ne $r.observed) { [string]$r.observed } else { '-' }
        $attesoStr    = if ($null -ne $r.expected) { [string]$r.expected } else { '-' }

        [void]$righeHtml.AppendLine("<tr>")
        [void]$righeHtml.AppendLine("  <td><span class='badge $classeStato'>$(& $escapeHtml "$simboloStato $etichettaStato")</span></td>")
        [void]$righeHtml.AppendLine("  <td>$(& $escapeHtml $gravita)</td>")
        [void]$righeHtml.AppendLine("  <td>$(& $escapeHtml $categoria)</td>")
        [void]$righeHtml.AppendLine("  <td><code>$(& $escapeHtml $id)</code></td>")
        [void]$righeHtml.AppendLine("  <td><strong>$(& $escapeHtml $titolo)</strong><br><small>$(& $escapeHtml $spiegazione)</small></td>")
        [void]$righeHtml.AppendLine("  <td>$(& $escapeHtml $attesoStr)</td>")
        [void]$righeHtml.AppendLine("  <td>$(& $escapeHtml $osservatoStr)</td>")
        [void]$righeHtml.AppendLine("</tr>")
    }

    $adminStr = if ($Report.environment.is_admin) { 'Yes' } else { 'No' }

    $html = @"
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Windows 11 Security Scanner Report</title>
<style>
  body { font-family: 'Segoe UI', Tahoma, sans-serif; background: #f4f6f9; color: #1e293b; margin: 0; padding: 24px; line-height: 1.5; }
  .container { max-width: 1200px; margin: 0 auto; background: #ffffff; border-radius: 8px; padding: 24px; box-shadow: 0 2px 8px rgba(0,0,0,0.08); }
  h1 { margin-top: 0; font-size: 22px; color: #0f172a; }
  .meta { background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 6px; padding: 12px 16px; margin-bottom: 20px; font-size: 14px; }
  .cards { display: flex; gap: 12px; flex-wrap: wrap; margin-bottom: 20px; }
  .card { flex: 1; min-width: 140px; padding: 12px 16px; border-radius: 6px; font-weight: 600; border: 1px solid #cbd5e1; }
  .card-pass { background: #dcfce7; color: #166534; border-color: #86efac; }
  .card-fail { background: #fee2e2; color: #991b1b; border-color: #fca5a5; }
  .card-unk  { background: #f1f5f9; color: #334155; border-color: #cbd5e1; }
  .card-na   { background: #f8fafc; color: #475569; border-color: #e2e8f0; }
  .card-err  { background: #ffedd5; color: #9a3412; border-color: #fdba74; }
  table { width: 100%; border-collapse: collapse; font-size: 14px; margin-bottom: 20px; }
  th, td { text-align: left; padding: 10px 12px; border-bottom: 1px solid #e2e8f0; vertical-align: top; }
  th { background: #f1f5f9; font-weight: 600; color: #334155; }
  .badge { display: inline-block; padding: 3px 8px; border-radius: 4px; font-weight: 600; font-size: 12px; white-space: nowrap; }
  .stato-superato    { background: #dcfce7; color: #166534; }
  .stato-fallito     { background: #fee2e2; color: #991b1b; }
  .stato-sconosciuto { background: #e2e8f0; color: #334155; }
  .stato-errore      { background: #ffedd5; color: #9a3412; }
  .stato-na          { background: #f1f5f9; color: #64748b; }
  .disclaimer { background: #fffbeb; border-left: 4px solid #f59e0b; padding: 12px 16px; font-size: 13px; color: #92400e; margin-top: 16px; }
  small { color: #475569; }
</style>
</head>
<body>
<div class="container">
  <h1>Windows 11 Security Scanner - Audit Report</h1>
  <div class="meta">
    <strong>Run ID:</strong> $(& $escapeHtml $Report.run_id) |
    <strong>Timestamp (UTC):</strong> $(& $escapeHtml $Report.timestamp) |
    <strong>Tool Version:</strong> $(& $escapeHtml $Report.tool_version) |
    <strong>Catalog:</strong> v$(& $escapeHtml $Report.catalog_version)<br>
    <strong>Environment:</strong> Windows 11 $(& $escapeHtml $Report.environment.edition) (Build $(& $escapeHtml $Report.environment.build)) |
    <strong>Language:</strong> $(& $escapeHtml $Report.environment.language) |
    <strong>Administrator:</strong> $adminStr |
    <strong>PowerShell:</strong> $(& $escapeHtml $Report.environment.ps_version)
  </div>
  <div class="cards">
    <div class="card card-pass">[OK] Passed: $($Report.summary.superato)</div>
    <div class="card card-fail">[X] Failed: $($Report.summary.fallito)</div>
    <div class="card card-unk">[?] Unknown: $($Report.summary.sconosciuto)</div>
    <div class="card card-na">[-] N/A: $($Report.summary.non_applicabile)</div>
    <div class="card card-err">[!] Errors: $($Report.summary.errore)</div>
  </div>
  <table>
    <thead>
      <tr>
        <th>Status</th>
        <th>Severity</th>
        <th>Category</th>
        <th>ID</th>
        <th>Control</th>
        <th>Expected Value</th>
        <th>Observed Value</th>
      </tr>
    </thead>
    <tbody>
$($righeHtml.ToString())
    </tbody>
  </table>
  <div class="disclaimer">
    <strong>Important notice:</strong> This report is the result of a static read-only security configuration audit.
    A passed control or compliant audit does not prove the absence of compromise or malware on the system.
  </div>
</div>
</body>
</html>
"@
    return $html
}

function Export-ReportHtml {
    <#
    .SYNOPSIS
        Writes a standalone HTML report file in UTF-8 without BOM.
    .PARAMETER Report
        The report object to export.
    .PARAMETER Catalogo
        Optional catalog object used to enrich displayed rows.
    .PARAMETER PercorsoFile
        Destination HTML file path.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [PSCustomObject]$Report,

        [Parameter(Mandatory = $false)]
        [PSCustomObject]$Catalogo = $null,

        [Parameter(Mandatory = $true)]
        [string]$PercorsoFile
    )

    $html = ConvertTo-ReportHtml -Report $Report -Catalogo $Catalogo
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($PercorsoFile, $html, $utf8NoBom)
}

function Export-TechnicalLog {
    <#
    .SYNOPSIS
        Writes a technical log file containing error details encountered during the scan.
    .PARAMETER Report
        The report object containing scan results.
    .PARAMETER PercorsoFile
        Destination log file path.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [PSCustomObject]$Report,

        [Parameter(Mandatory = $true)]
        [string]$PercorsoFile
    )

    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("=== WINDOWS SECURITY SCANNER TECHNICAL LOG ===")
    [void]$sb.AppendLine("Run ID:    $($Report.run_id)")
    [void]$sb.AppendLine("Timestamp: $($Report.timestamp)")
    [void]$sb.AppendLine("Edition:   $($Report.environment.edition) (Build $($Report.environment.build))")
    [void]$sb.AppendLine("Admin:     $($Report.environment.is_admin)")
    [void]$sb.AppendLine("---------------------------------------------")

    $conErrori = 0
    if ($null -ne $Report.results) {
        foreach ($r in $Report.results) {
            if ($null -ne $r.error -and $r.error -ne '') {
                $conErrori++
                [void]$sb.AppendLine("[$($r.control_id)] Status: $($r.status)")
                [void]$sb.AppendLine("  Technical detail: $($r.error)")
                [void]$sb.AppendLine("")
            }
        }
    }

    if ($conErrori -eq 0) {
        [void]$sb.AppendLine("No technical errors recorded during the scan.")
    }

    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($PercorsoFile, $sb.ToString(), $utf8NoBom)
}
